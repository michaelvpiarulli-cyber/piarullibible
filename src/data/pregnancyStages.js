/** @param {number} week pregnancy week 1–40 */
export function pregnancyStageForWeek(week) {
  const w = Math.min(40, Math.max(1, Math.round(Number(week) || 1)));
  const stage = STAGES[w - 1];
  return { ...stage, tip: stage.tips[0], fact: stage.facts[0] };
}

/**
 * Daily stage card: weekly forming story + fact/tip for this day in the week.
 * @param {number} week
 * @param {number} [pregnancyDay] catalog/gestational day 1–280
 */
export function pregnancyStageForDay(week, pregnancyDay = 1) {
  const w = Math.min(40, Math.max(1, Math.round(Number(week) || 1)));
  const stage = STAGES[w - 1];
  const day = Math.min(280, Math.max(1, Math.round(Number(pregnancyDay) || 1)));
  const idx = (day - 1) % 7;
  return {
    week: stage.week,
    title: stage.title,
    forming: stage.forming,
    fact: stage.facts[idx],
    tip: stage.tips[idx],
    dayInWeek: idx + 1,
  };
}

